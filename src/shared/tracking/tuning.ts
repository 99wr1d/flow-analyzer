export const HIDDEN_BETTER_MARGIN = 0.05

/** Выход из пережидания: кандидат дальше этого (в высотах игрока) от прогноза молча не принимается — после срока вопрос. */
export const RECOVER_FAR_DIST = 1.0

/** «Сомнительная» рамка: примета хуже APPEARANCE_REJECT, но не хуже этого, и стоит не дальше DOUBT_DIST высот от прогноза. */
export const DOUBT_APPEARANCE = 0.45
export const DOUBT_DIST = 0.5

/**
 * «Грязная» примета (старт рядом с соседом): единственный кандидат принимается молча, только если он продолжает движение —
 * почти там же, где прогноз (в высотах игрока) и с большим перекрытием с ним. Любой другой одиночка — сомнение: ждём и спрашиваем.
 */
export const DIRTY_CONTINUITY_DIST = 0.2
export const DIRTY_CONTINUITY_IOU = 0.35
/**
 * …и только если по примете он явно ближе к нашей, чем к приметам стартовых соседей (на столько по расстоянию 0..1).
 * Если наша примета сама ближе к соседской, чем на эту величину, она слишком «грязная» для сравнения: исключения нет.
 */
export const DIRTY_LOOK_MARGIN = 0.2
/** …и его примета не дальше этого от нашей (строже APPEARANCE_REJECT: третий игрок не должен проходить «по остатку»). */
export const DIRTY_APPEARANCE_CAP = 0.2

/**
 * Рамка резко выше последней принятой (наш игрок был виден частично, а теперь «рамка» охватывает и соседа) считается слитой
 * и молча не принимается, пока идёт пережидание (первые COAST_SECONDS).
 */
export const HEIGHT_JUMP_RATIO = 1.5

/**
 * После подтверждения пользователем нечистой рамки (слитой, высокой, перекрытой) примета заморожена; снимает заморозку
 * уверенная чистая рамка размера последней чистой, чья примета не дальше этого от замороженной.
 */
export const FROZEN_CONFIRM_APPEARANCE = 0.2

/**
 * Несколько целей (Связка): две цели не могут владеть одной рамкой. Рамки двух целей «слились», если это одна и та же
 * детекция либо две почти совпадающие (IoU не меньше CONVERGE_IOU). Две разные детекции, пусть и тесно стоящие
 * (IoU 0,3 у игроков, проходящих друг мимо друга), одним человеком не считаются.
 */
export const CONVERGE_IOU = 0.5

/**
 * Цепочка непрерывности (Связка): пока цель «пережидает» рядом с игроком похожей приметы (расстояние приметы меньше
 * CHAIN_SIMILAR_LOOK, игрок не дальше CHAIN_NEIGHBOUR_DIST высот), её личность по прогнозу не доказана (при отскоке
 * прогноз как раз ведёт к чужому). Поэтому параллельно цепляем сырые детекции кадр за кадром: на каждом кадре цепочка
 * переходит к детекции с наименьшим смещением центра (в высотах) от прошлой рамки цепочки. Звено надёжно, если
 * смещение не больше CHAIN_MAX_SHIFT (= ворота обычного ведения), ближайшая детекция лучше второй не меньше чем на
 * CHAIN_RUNNER_UP высоты и её не занимает другая цепочка или уверенно ведомая цель. Иначе цепочка разорвана.
 * Когда трекер цели снова уверен: цепочка цела и ведёт к той же детекции — молча принимаем; к другой — вопрос с обеими;
 * разорвана — вопрос. CHAIN_RUNNER_UP = 0,15 высоты (13,5 px при росте 90) — запас на шум рамок ±2–4 px и ±5 % высоты:
 * ближе этого два игрока на шаге цепочки не различимы, цепочка рвётся и цель спрашивают (проход насквозь со сдвигом
 * по вертикали до ~0,3 высоты тоже даёт вопрос). От порога молчаливые подмены не зависят: общая детекция, спорная
 * рамка без доказанной цепочки и пережидающие цели никогда не дают уверенной рамки, а вопросы не прячут настоящего игрока.
 */
export const CHAIN_SIMILAR_LOOK = APPEARANCE_REJECT
export const CHAIN_NEIGHBOUR_DIST = GATE_MAX
export const CHAIN_MAX_SHIFT = GATE_BASE
export const CHAIN_RUNNER_UP = 0.15
