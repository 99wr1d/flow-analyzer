import type { Mat3 } from '../pitch/linalg'

/**
 * Движение камеры между двумя соседними кадрами.
 * H переводит точку кадра index−1 в точку кадра index (точки — в долях кадра, применять через applyH).
 */
export interface FrameMotion {
  index: number
  H: Mat3
  /** Оценка движения признана надёжной; иначе через этот кадр цепочку не строим. */
  reliable: boolean
  /** Число согласованных пар точек, на которых построена H. */
  inliers: number
}

/** Максимальная длина участка цепочки (в кадрах); дальше накопленная ошибка делает матрицу бесполезной. */
export const MAX_CHAIN_SPAN = 2000

// Оценка движения между двумя кадрами (estimate.ts). Пиксельные пороги заданы для кадра шириной
// MOTION_REF_WIDTH и масштабируются пропорционально фактической ширине кадра.

/** Ширина кадра, для которой заданы пороги в пикселях. */
export const MOTION_REF_WIDTH = 480
/** Надёжно: не меньше стольких согласованных точек… */
export const MOTION_MIN_INLIERS = 40
/** …и не меньше этой доли от всех найденных угловых точек. */
export const MOTION_MIN_INLIER_SHARE = 0.4
/** Надёжно: выпуклая оболочка согласованных точек занимает не меньше этой доли кадра. */
export const MOTION_MIN_HULL_SHARE = 0.15
/** Надёжно: среднеквадратичная ошибка подгонки по согласованным точкам не больше (px при MOTION_REF_WIDTH). */
export const MOTION_MAX_RMS_PX = 1
/** Порог ошибки RANSAC: точка согласована, если модель переносит её не дальше (px при MOTION_REF_WIDTH). */
export const MOTION_RANSAC_THRESHOLD_PX = 1.5
/** Гомография — только при стольких согласованных точках; иначе подобие (сдвиг + масштаб + поворот). */
export const MOTION_HOMOGRAPHY_MIN_INLIERS = 80
/** Гомография — только если согласованные точки покрывают такую долю кадра; иначе подобие. */
export const MOTION_HOMOGRAPHY_MIN_HULL_SHARE = 0.3
/** Доля ширины/высоты кадра у краёв, где угловые точки не берутся (логотипы, рамки, обрезка). */
export const MOTION_EDGE_MARGIN = 0.05
/** Масштаб между соседними кадрами вне [1/x, x] — не движение камеры, а сбой оценки (ненадёжно). */
export const MOTION_MAX_SCALE_STEP = 1.25
