import type { Mat3 } from '../pitch/linalg'

/**
 * Движение камеры между двумя соседними кадрами.
 * H переводит точку кадра index−1 в точку кадра index (точки — в долях кадра, применять через applyH).
 */
export interface FrameMotion {
  index: number
  H: Mat3
  /** Оценка движения признана надёжной; иначе через этот кадр цепочку не строим. */
  reliable: boolean
  /** Число согласованных пар точек, на которых построена H. */
  inliers: number
}

/** Максимальная длина участка цепочки (в кадрах); дальше накопленная ошибка делает матрицу бесполезной. */
export const MAX_CHAIN_SPAN = 2000

// Оценка движения между двумя кадрами (estimate.ts). Пиксельные пороги заданы для кадра шириной
// MOTION_REF_WIDTH и масштабируются пропорционально фактической ширине кадра.

/** Ширина кадра, для которой заданы пороги в пикселях. */
export const MOTION_REF_WIDTH = 480
/** Надёжно: не меньше стольких согласованных точек… */
export const MOTION_MIN_INLIERS = 40
/**
 * …и не меньше этой доли от найденных угловых точек без отброшенных проверкой периодичности (полосы газона)
 * и без неподвижной графики; потерянные потоком точки в знаменателе остаются.
 */
export const MOTION_MIN_INLIER_SHARE = 0.4
/** Надёжно: выпуклая оболочка согласованных точек занимает не меньше этой доли кадра. */
export const MOTION_MIN_HULL_SHARE = 0.15
/** Надёжно: среднеквадратичная ошибка подгонки по согласованным точкам не больше (px при MOTION_REF_WIDTH). */
export const MOTION_MAX_RMS_PX = 1
/** Порог ошибки RANSAC: точка согласована, если модель переносит её не дальше (px при MOTION_REF_WIDTH). */
export const MOTION_RANSAC_THRESHOLD_PX = 1.5
/** Доля ширины/высоты кадра у краёв, где угловые точки не берутся (логотипы, рамки, обрезка). */
export const MOTION_EDGE_MARGIN = 0.05
/** Масштаб между соседними кадрами вне [1/x, x] — не движение камеры, а сбой оценки (ненадёжно). */
export const MOTION_MAX_SCALE_STEP = 1.25

/**
 * Ненадёжно, если несогласованные с найденным движением точки сами дают второе движение
 * не меньше этой доли от числа согласованных и не меньше MOTION_MIN_INLIERS точек (неясно, какое из двух — камера).
 */
export const MOTION_RIVAL_SHARE = 0.3

/**
 * Неподвижная графика трансляции (табло, логотип, подписи): точка с потоком меньше MOTION_STATIC_FLOW_PX
 * (px при MOTION_REF_WIDTH) не участвует в подгонке, если медианный поток всех прослеженных точек не меньше
 * MOTION_STATIC_MEDIAN_PX — то есть основная часть сцены едет. Если камера стоит (медиана мала), точки не
 * отбрасываются: единичное движение, надёжно. Порог 0.15 — потолок шума потока на неподвижных пикселях
 * (замер: у табло и логотипа поток < 0.1 px почти всегда); медиана 0.3 — вдвое выше.
 */
export const MOTION_STATIC_FLOW_PX = 0.15
export const MOTION_STATIC_MEDIAN_PX = 0.3

/**
 * Ненадёжно, если свободная гомография по тем же точкам отличается от модели камеры больше (px при MOTION_REF_WIDTH,
 * среднеквадратично по согласованным точкам широкого порога): данные просят перекоса/перспективы, которых камера не даёт.
 */
export const MOTION_MAX_MODEL_DEVIATION_PX = 0.75

/**
 * Неподвижных точек (см. MOTION_STATIC_FLOW_PX) больше этой доли прослеженных — ненадёжно: либо гигантское табло,
 * либо камера стоит, а едет большинство, и «графикой» назван настоящий фон.
 */
export const MOTION_MAX_STATIC_SHARE = 0.4
/**
 * Ненадёжно, если среди согласованных точек больше этой доли стоит на месте, хотя модель обещает им сдвиг
 * ≥ 3·MOTION_STATIC_FLOW_PX (медленная панорама, при которой графика не снимается по медиане).
 */
export const MOTION_MAX_HIDDEN_STATIC_SHARE = 0.15

/** Поворот камеры в плоскости кадра между соседними кадрами больше (рад) — не движение камеры, сбой оценки. */
export const MOTION_MAX_ROLL = 0.1

/** Окно Лукаса–Канаде: (2r+1)² пикселей. */
export const LK_RADIUS = 5
export const LK_MAX_ITER = 20
/** Итерации потока останавливаются, когда шаг меньше (px уровня пирамиды). */
export const LK_EPS = 0.01
/** Порог «текстурности» окна: наименьшее собственное число структурного тензора на пиксель окна (уровни яркости²). */
export const MIN_EIG = 4
/** Средняя разница яркости окна после совмещения больше этого — точка потеряна (другое содержимое). */
export const LK_MAX_RESIDUAL = 12
/** Ошибка проверки потока «туда-обратно» больше (px при MOTION_REF_WIDTH) — точка потеряна. */
export const LK_MAX_FB_ERROR = 0.5
/**
 * Проверка неоднозначности (периодическая текстура: полосы газона, сетка): окно точки похоже само на себя
 * со сдвигом — поток может «перепрыгнуть» на соседний период. Ищем такой сдвиг до AMBIGUITY_RADIUS
 * (px при MOTION_REF_WIDTH) на уровнях пирамиды 1/2 и 1/4.
 */
export const AMBIGUITY_RADIUS = 40
/** Окно неоднозначно, если со сдвигом средняя разница яркости меньше этой доли его собственного контраста. */
export const AMBIGUITY_RATIO = 0.5
